"""Store port. Two adapters: MemoryStore (tests/mock) and PgStore (Supabase Postgres + pgvector).

Rows are plain dicts. Business rules (authorization, policy) live ABOVE this layer; the store only
persists. Atomic state transitions (`transition_action`, `consume_approval`) are the concurrency
primitives that make idempotency and anti-replay safe.
"""

from __future__ import annotations

from typing import Any, Protocol

from app.models import Chunk

Row = dict[str, Any]


class Store(Protocol):
    # master data / tools
    def get_equipment(self, equipment_id: str) -> Row | None: ...
    def latest_sensor_readings(self, equipment_id: str) -> list[Row]: ...
    def list_failures(self, equipment_id: str, limit: int = 10) -> list[Row]: ...
    # rag
    def upsert_chunks(self, chunks: list[tuple[Chunk, list[float]]]) -> int: ...
    def search_chunks(self, embedding: list[float], plant_id: str, equipment_type: str, k: int, min_score: float) -> list[Chunk]: ...
    # incidents
    def get_incident(self, incident_id: str) -> Row | None: ...
    def create_incident(self, row: Row) -> Row: ...
    def touch_incident(self, incident_id: str, status: str) -> None: ...
    def add_run(self, row: Row) -> None: ...
    def finish_run(self, run_id: str, status: str, steps: int, node_timings: dict[str, float]) -> None: ...
    def get_run(self, run_id: str) -> Row | None: ...
    def list_runs(self, incident_id: str) -> list[Row]: ...
    def add_observations(self, incident_id: str, run_id: str, user: str, rows: list[Row]) -> None: ...
    def list_observations(self, incident_id: str) -> list[Row]: ...
    def add_hypotheses(self, incident_id: str, run_id: str, user: str, rows: list[Row]) -> None: ...
    def list_hypotheses(self, incident_id: str) -> list[Row]: ...
    # actions / approvals
    def insert_action(self, row: Row) -> tuple[Row, bool]: ...
    def get_action(self, action_id: str) -> Row | None: ...
    def list_actions(self, incident_id: str) -> list[Row]: ...
    def transition_action(self, action_id: str, from_status: str, to_status: str, result: Row | None = None) -> bool: ...
    def insert_approval(self, row: Row) -> None: ...
    def get_approval(self, approval_id: str) -> Row | None: ...
    def approval_for_action(self, action_id: str) -> Row | None: ...
    def decide_approval(self, approval_id: str, from_status: str, to_status: str, decided_by: str) -> bool: ...
    # audit / policy
    def append_audit(self, row: Row) -> None: ...
    def list_audit(self, incident_id: str) -> list[Row]: ...
    def save_policy_version(self, row: Row) -> None: ...
    def active_policy_version(self) -> Row | None: ...
